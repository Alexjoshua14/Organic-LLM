/**
 * Resolve a workbench manpage by topic name or alias.
 * Defaults to `"overview"` when omitted; returns a helpful index fallback on unknown topics.
 */
export function getWorkbenchManpage(topic?: string | null): {
  topic: WorkbenchManpageTopic;
  known: boolean;
  manpage: string;
  availableTopics: ReadonlyArray<WorkbenchManpageTopic>;
} {
  const raw = topic?.trim().toLowerCase() ?? "";

  if (!raw) {
    return {
      topic: "overview",
      known: true,
      manpage: MANPAGES.overview,
      availableTopics: WORKBENCH_MANPAGE_TOPICS,
    };
  }

  const resolved = TOPIC_ALIASES[raw];

  if (resolved) {
    return {
      topic: resolved,
      known: true,
      manpage: MANPAGES[resolved],
      availableTopics: WORKBENCH_MANPAGE_TOPICS,
    };
  }

  return {
    topic: "overview",
    known: false,
    manpage: `Unknown manpage topic "${topic}". Showing overview:\n\n${MANPAGES.overview}`,
    availableTopics: WORKBENCH_MANPAGE_TOPICS,
  };
}
